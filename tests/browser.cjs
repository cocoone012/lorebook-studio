async function assertCenteredSave(page) {
  const button = await page.locator('#save').boundingBox();
  const label = await page.locator('#save-label').boundingBox();
  assert.ok(Math.abs(button.x + button.width / 2 - label.x - label.width / 2) < 1, 'commit text horizontally centered');
  assert.ok(Math.abs(button.y + button.height / 2 - label.y - label.height / 2) < 1, 'commit text vertically centered');
  const arrow = await page.locator('#save .save-direction').boundingBox();
  assert.ok(arrow.x - label.x - label.width >= 6, 'commit arrow does not overlap the final character');
}
async function assertStackedSections(page) {
  const ids = ['description-original', 'description-source-toolbar', 'description-source-translation', 'description-editor-heading', 'content', 'description-toolbar', 'translation-text'];
  const boxes = [];
  for (const id of ids) boxes.push(await page.locator('#' + id).boundingBox());
  for (let i = 1; i < boxes.length; i++) assert.ok(boxes[i].y >= boxes[i - 1].y + boxes[i - 1].height - 1, 'mobile sections keep their full vertical order');
  const imports = await page.locator('.description-import-actions').boundingBox();
  assert.ok(imports.y >= boxes[2].y + boxes[2].height);
  assert.ok(imports.y + imports.height <= boxes[3].y);
  const workspace = await page.locator('#work-area').boundingBox();
  const first = await page.locator('#description-ai-load').boundingBox();
  const second = await page.locator('#load-description').boundingBox();
  assert.ok(Math.abs((first.x + second.x + second.width) / 2 - workspace.x - workspace.width / 2) < 1, 'import buttons centered between sections');
  assert.equal(first.y, second.y);
  assert.equal(boxes[0].x, boxes[4].x);
  assert.equal(boxes[0].width, boxes[4].width);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await assertCenteredSave(page);
}
